	jsr FNDLIN	//FIND LINE .GE. [NUMLIN].
	jsr CHRGOT	//GET LAST CHARACTER.
	beq LSTEND	//IF END OF LINE, # IS THE END.
	cmp #MINUTK	//DASH?
	bne FLNRTS	//IF NOT, SYNTAX ERROR.
	jsr CHRGET	//GET NEXT CHAR.
	jsr LINGET	//GET END #.
	bne FLNRTS	//IF NOT TERMINATOR, ERROR.
