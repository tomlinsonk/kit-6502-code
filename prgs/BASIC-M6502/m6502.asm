	bcc FADDA	//BR IF ARGEXP.LT.FACEXP.
	sty FACEXP	//RESULTING EXPONENT.
	ldy ARGSGN	//SINCE ARG IS BIGGER, IT'S
	sty FACSGN	//SIGN IS SIGN OF RESULT.
	eor #$ff	//SHIFT A NEGATIVE NUMBER OF PLACES.
