CHEAD:	ldy #1
	lda (INDEX),y	//ARRIVED AT DOUBLE ZEROES?
	beq LNKRTS
	ldy #4
CZLOOP:	iny	//THERE IS AT LEAST ONE BYTE.
	lda (INDEX),y
	bne CZLOOP	//NO, CONTINUE SEARCHING.
	iny	//GO ONE BEYOND.
	tya
	adc INDEX
	tax
	ldy #0
	sta (INDEX),y
	lda INDEX+1
	adc #0
	iny
	sta (INDEX),y
	stx INDEX
	sta INDEX+1
	bcc CHEAD	//ALWAYS BRANCHES.
