	sta LINWID	//WORK AFTER MOVING A NEW LINE IN BUF
//INTO THE PROGRAM
	lda #NCMPOS
	sta NCMWID
	ldx #RNDX+4-CHRGET
MOVCHG:	lda INITAT-1,X
	sta CHRGET-1,X	//MOVE TO RAM.
	dex
	bne MOVCHG
	lda #STRSIZ
