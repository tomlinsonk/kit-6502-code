	pla	//GET RID OF "NEWSTT" RTS ADDR.
	lda LINNUM	//SEE IF IT WAS EXISTENT.
	ora LINNUM+1
	bne LIST4	//IT WAS TYPED.
	lda #255
	sta LINNUM
	sta LINNUM+1	//MAKE IT HUGE.
